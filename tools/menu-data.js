
/* ===================== เมนูจริงจากใบเมนูของร้าน =====================
   เครป: แป้ง 15 บาท แล้วบวกไส้ที่เลือก (ไส้ละ 5–10 บาท) ซอสราดฟรี
   โตเกียว: ไส้คาวคิดตามจำนวนไส้ (2 ไส้ 10 / 3 ไส้ 15) จึงแยกเป็น 2 เมนู */
function shopMenu(){
  const A = (name, price, group) => ({ id: uid(), name, price, group });

  const ไส้คาวเครป = [
    ['พิซซ่า',5], ['พริกเผา',5], ['ไก่หยอง',5],
    ['โบโลน่า',5], ['ไก่สับ',5], ['ไส้กรอก',5],
    ['ปูอัด',5], ['ไข่นก',5], ['ไข่ไก่',10], ['ยำสาหร่าย',10]
  ].map(([n,p]) => A(n, p, 'ไส้คาว'));

  const ไส้หวานเครป = [
    ['แยมสตรอเบอร์รี่',5], ['แยมบลูเบอร์รี่',5], ['ช็อกโกแลต',5],
    ['เยลลี่',5], ['โอริโอ้',5], ['ลูกเกด',5],
    ['มาร์ชเมลโลว์',5], ['ฝอยทอง',10]
  ].map(([n,p]) => A(n, p, 'ไส้หวาน'));

  const ซอสฟรี = ['ซอสพริก','ซอสมะเขือเทศ','มายองเนส','นมข้น','ช็อกโกแลต']
    .map(n => A(n, 0, 'ราดซอส (ฟรี)'));

  const ไส้โตเกียว = ['พริกเผา','พิซซ่า','ไข่นก','ปูอัด','ไส้กรอก','ไก่สับ','โบโลน่า','ไก่หยอง','สาหร่าย']
    .map(n => A(n, 0, 'ไส้โตเกียว (คาว)'));

  const ไส้หวานโตเกียว = ['ครีม','ครีมข้าวโพด','เผือกกวน'].map(n => A(n, 0, 'ไส้โตเกียว (หวาน)'));

  const M = (name, price, addons) => ({ id: uid(), name, price, qtyPerDay: 0, items: [], addons });

  return [
    M('เครป แป้งวานิลา', 15, [...ไส้คาวเครป, ...ไส้หวานเครป, ...ซอสฟรี]),
    M('เครป แป้งชาร์โคล', 15, [...ไส้คาวเครป.map(a=>({...a,id:uid()})),
                               ...ไส้หวานเครป.map(a=>({...a,id:uid()})),
                               ...ซอสฟรี.map(a=>({...a,id:uid()}))]),
    M('โตเกียวไส้คาว 2 ไส้', 10, [...ไส้โตเกียว, ...ซอสฟรี.map(a=>({...a,id:uid()}))]),
    M('โตเกียวไส้คาว 3 ไส้', 15, [...ไส้โตเกียว.map(a=>({...a,id:uid()})),
                                  ...ซอสฟรี.map(a=>({...a,id:uid()}))]),
    M('โตเกียวไส้หวาน 6 ชิ้น', 25, [...ไส้หวานโตเกียว,
                                     ...ซอสฟรี.map(a=>({...a,id:uid()}))]),
    M('ไข่ป๋วง 8 ชิ้น', 25, []),
    M('แพนเค้กมินิ 15 ชิ้น', 25, []),
    M('แพนเค้กไส้กรอก 3 ชิ้น', 20, [])
  ];
}

// ใส่เมนูจริงลงแอป โดยไม่แตะยอดขาย/รายจ่ายที่บันทึกไว้แล้ว
function loadShopMenu(){
  const had = db.menus.length;
  if(had && !confirm('จะแทนที่เมนูเดิมทั้งหมดด้วยเมนูจากใบเมนู\n(ยอดขายกับรายจ่ายที่บันทึกไว้ไม่หาย)\nยืนยันไหม?')) return;
  db.menus = shopMenu();
  delete db.isDemo;
  save(); tab = 'menu'; openMenuId = null; render();
  toast('ใส่เมนูให้แล้ว ' + db.menus.length + ' เมนู');
}
